#!/usr/bin/env python3
"""SAPI-1 tables for BomberNet: logical code -> CGA-1V cell, from the MZ tables.

Input:
  BomberNet/c/platform/mz/tables.c   game_table and title_table (logical code -> MZ display code, attribute)
  the MZ-700 character ROM            4096 bytes, 512 glyphs of 8 bytes, bit 0 = leftmost pixel; not in the
                                      repo (Sharp): --cgrom, $MZ_CGROM, or ../SAPI-Bomberman-private/cgrom.bin

The CGA-1V runs in EGA mode: a byte is 4 pixels (high nibble, D7 leftmost) and an attribute (low nibble); the
colour index is attribute * 2 + pixel (COLMASK 1Fh), so an attribute is a pair (background, foreground). A cell is
8 x 8 pixels = 2 bytes x 8 lines, the lines 80 bytes apart. The MZ attribute is foreground in bits 6-4, background in
bits 2-0, bit 7 selects the second half of the character ROM.

Written to sapi/tables.[ch]:
  sapi_cells        every (glyph, attribute) the two tables use, rendered in advance, 16 bytes each
  sapi_game_idx     logical code -> cell (game mode)
  sapi_title_idx    logical code -> cell (title mode)
  sapi_glyphs       the glyphs of the game table, 8 bytes, bit 7 leftmost (the live renderer)
  sapi_game_glyph   logical code -> glyph (game mode)
  sapi_player_attr  CGA attribute of each player's colour (plat_player_colour)
  sapi_palette      Bt476 colours 0..31: R, G, B (6 bits)
"""
import argparse
import os
import re

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.join(here, '..')

ap = argparse.ArgumentParser()
ap.add_argument('--cgrom', default=os.environ.get('MZ_CGROM',
                os.path.join(root, '..', 'SAPI-Bomberman-private', 'cgrom.bin')))
a = ap.parse_args()
cg = open(a.cgrom, 'rb').read()
assert len(cg) == 4096, f'{a.cgrom}: {len(cg)} bytes, expected 4096'
src = open(os.path.join(root, 'BomberNet', 'c', 'platform', 'mz', 'tables.c')).read()

# MZ colours: bit 0 blue, bit 1 red, bit 2 green (as SAPI-Bomberman, 6-bit RGB of the Bt476)
MZ_RGB = [(0, 0, 0), (0, 0, 63), (63, 0, 0), (63, 0, 63), (0, 63, 0), (0, 63, 63), (63, 63, 0), (63, 63, 63)]
PLAYER_MZ_ATTR = [0x40, 0x60, 0x70, 0x10]      # plat_mz.c player_attrs: green, yellow, white, blue


def table(name):
    i = src.index(name + '[512] = {')
    j = src.index('};', i)
    t = [int(x, 0) for x in re.findall(r'0x[0-9a-fA-F]+', src[i:j])]
    assert len(t) == 512, name
    return t


attrs = []                                      # CGA attribute -> (background, foreground) MZ colours


def attr_of(mz):
    pair = (mz & 7, (mz >> 4) & 7)
    if pair not in attrs:
        attrs.append(pair)
    return attrs.index(pair)


def glyph(display, mz):
    """MZ glyph (bit 0 leftmost) -> bit 7 leftmost"""
    n = display | (mz & 0x80) << 1
    return bytes(int(f'{b:08b}'[::-1], 2) for b in cg[n * 8:n * 8 + 8])


def render(g, at):
    out = bytearray()
    for b in g:
        out += bytes([(b & 0xF0) | at, ((b << 4) & 0xF0) | at])
    return bytes(out)


cells, cell_index = [], {}


def cell(g, at):
    key = render(g, at)
    if key not in cell_index:
        cell_index[key] = len(cells)
        cells.append(key)
    return cell_index[key]


game, title = table('game_table'), table('title_table')
player_attr = bytes(attr_of(m) for m in PLAYER_MZ_ATTR)
game_idx = bytes(cell(glyph(game[2 * c], game[2 * c + 1]), attr_of(game[2 * c + 1])) for c in range(256))
title_idx = bytes(cell(glyph(title[2 * c], title[2 * c + 1]), attr_of(title[2 * c + 1])) for c in range(256))
assert len(cells) <= 256, len(cells)
assert len(attrs) <= 16, attrs

glyphs, glyph_index = [], {}
for c in range(256):
    g = glyph(game[2 * c], game[2 * c + 1])
    if g not in glyph_index:
        glyph_index[g] = len(glyphs)
        glyphs.append(g)
game_glyph = bytes(glyph_index[glyph(game[2 * c], game[2 * c + 1])] for c in range(256))

palette = bytearray()
for k in range(16):
    bg, fg = attrs[k] if k < len(attrs) else (0, 0)
    palette += bytes(MZ_RGB[bg] + MZ_RGB[fg])


def carray(name, data, per=16, comment=None):
    lines = [f'/* {comment} */'] if comment else []
    lines.append(f'const uint8_t {name}[{len(data)}] = {{')
    for i in range(0, len(data), per):
        lines.append('  ' + ', '.join(f'0x{b:02x}' for b in data[i:i + per]) + ',')
    lines += ['};', '']
    return '\n'.join(lines)


out = os.path.join(root, 'sapi')
head = '/* Generated by tools/make_tables.py from BomberNet/c/platform/mz/tables.c - do not edit. */'
with open(os.path.join(out, 'tables.c'), 'w', newline='\n') as f:
    f.write('\n'.join([
        head, '#include <stdint.h>', '#include "tables.h"', '',
        carray('sapi_cells', b''.join(cells), 16,
               f'{len(cells)} cells rendered in advance, 16 bytes each (line 0 left, right, line 1 ...)'),
        carray('sapi_game_idx', game_idx, 16, 'game mode: logical code -> cell'),
        carray('sapi_title_idx', title_idx, 16, 'title mode: logical code -> cell'),
        carray('sapi_glyphs', b''.join(glyphs), 8, f'{len(glyphs)} glyphs of the game table, bit 7 leftmost'),
        carray('sapi_game_glyph', game_glyph, 16, 'game mode: logical code -> glyph'),
        carray('sapi_player_attr', player_attr, 4, 'CGA attribute of each player colour'),
        carray('sapi_palette', palette, 12,
               f'Bt476 colours 0..31 (R, G, B, 6 bits): attribute * 2 = background, + 1 = foreground; '
               f'{len(attrs)} attributes used')]))
with open(os.path.join(out, 'tables.h'), 'w', newline='\n') as f:
    f.write('\n'.join([
        head, '#ifndef TABLES_H', '#define TABLES_H', '#include <stdint.h>',
        f'extern const uint8_t sapi_cells[{len(cells) * 16}];',
        'extern const uint8_t sapi_game_idx[256];', 'extern const uint8_t sapi_title_idx[256];',
        f'extern const uint8_t sapi_glyphs[{len(glyphs) * 8}];', 'extern const uint8_t sapi_game_glyph[256];',
        'extern const uint8_t sapi_player_attr[4];', 'extern const uint8_t sapi_palette[96];', '#endif', '']))
print(f'sapi/tables.[ch]: {len(cells)} cells, {len(glyphs)} glyphs, {len(attrs)} attributes {attrs}, '
      f'{len(cells) * 16 + 512 + len(glyphs) * 8 + 256 + 4 + 96} bytes')
